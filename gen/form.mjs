// A song skeleton from a mood and a length: sections with roles, bar counts, harmony and axis values shaped by the
// mood's overlay vector, ready for the material-first pass (written hooks, pack instruments, a counter-line).
// usage: node gen/form.mjs [--mood=euphoric] [--bars=64] [--seed=N] > songs/new.strudel
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { OVERLAYS, HARMONY } from '../lib/vocab.mjs';
import { fmt } from '../lib/resolve.mjs';
import { progressionFor } from '../lib/harmony.mjs';
import { prng, pick as pickBy } from '../lib/random.mjs';

// per mood: the mode, the verse progression and the climax progression (words from lib/harmony.json), a tempo.
// A mood is an overlay word (lib/overlays.json) with a row here; MOODS lists the ones that have both.
const FEEL = {
  sad: { mode: 'minor', verse: 'unresolved', climax: 'circular', bpm: 84 },
  happy: { mode: 'major', verse: 'pop', climax: 'resolved', bpm: 118 },
  ominous: { mode: 'phrygian', verse: 'static', climax: 'tense', bpm: 96 },
  euphoric: { mode: 'major', verse: 'pop', climax: 'epic', bpm: 126 },
  hypnotic: { mode: 'dorian', verse: 'static', climax: 'unresolved', bpm: 120 },
  chaotic: { mode: 'phrygian', verse: 'tense', climax: 'circular', bpm: 150 },
  playful: { mode: 'mixolydian', verse: 'pop', climax: 'resolved', bpm: 112 },
  cinematic: { mode: 'minor', verse: 'unresolved', climax: 'epic', bpm: 72 },
};
// the arc, as shares of the length: role and the parts each section carries with their base values (0.5 = baseline)
const ARC = [
  { name: 'intro', share: 2, role: 'establish', parts: { drums: { density: .3, space: .6 }, pad: { space: .7, articulation: .2 } } },
  { name: 'verse', share: 4, role: 'develop', parts: { drums: { density: .6 }, bass: { weight: .65 }, melody: { density: .5 }, pad: { space: .55 } } },
  { name: 'build', share: 2, role: 'develop', parts: { drums: { density: .7, drive: .7, variation: .6 }, bass: { weight: .7, density: .6 }, melody: { density: .6, brightness: .6 }, pad: { space: .5 }, fx: { riser: 4 } } },
  { name: 'drop', share: 4, role: 'climax', parts: { drums: { density: .9, drive: .8, articulation: .7 }, bass: { weight: .9, density: .75 }, melody: { density: .7, width: .7 }, pad: { width: .8, brightness: .6 }, fx: { impact: true } } },
  { name: 'breakdown', share: 2, role: 'release', parts: { melody: { density: .3, space: .7 }, pad: { space: .8, brightness: .35 } } },
  { name: 'outro', share: 2, role: 'release', parts: { drums: { density: .3, space: .6 }, pad: { space: .7, articulation: .2 } } },
];
const ROOTS = ['C', 'D', 'Eb', 'E', 'F', 'G', 'A', 'Bb'];
const KITS = ['RolandTR808', 'RolandTR909', 'LinnDrum', 'AkaiLinn'];
export const MOODS = Object.keys(FEEL).filter((m) => OVERLAYS[m]);
const clamp = (x) => Math.min(1, Math.max(0, x));
const SHARES = ARC.reduce((n, s) => n + s.share, 0); // 16

export function generate(seed = 1, { mood = 'euphoric', bars = 64 } = {}) {
  if (!MOODS.includes(mood)) throw new Error(`unknown mood "${mood}" (one of ${MOODS.join(', ')})`);
  const rnd = prng(seed); // the song's own generator
  const pick = (a) => pickBy(rnd, a); // middle bits: the LCG's top bits barely move between neighbouring seeds, so seeds 1..30 would all pick the same root
  const feel = FEEL[mood], vec = OVERLAYS[mood];
  const unit = Math.max(1, Math.round(bars / SHARES)); // bars per share: 64 bars -> 4, so intro (share 2) is 8 bars
  const key = `${pick(ROOTS)}:${feel.mode}`, kit = pick(KITS);
  const sections = ARC.map((s) => {
    const parts = Object.entries(s.parts).map(([layer, base]) => {
      const attrs = { ...base };
      for (const [axis, d] of Object.entries(vec)) if (axis in attrs || (layer !== 'fx' && Math.abs(d) >= .2)) attrs[axis] = clamp((attrs[axis] ?? .5) + d); // the mood pushes every part where it pushes hard, and where the part already speaks
      const body = Object.entries(attrs).map(([k, v]) => `${k}: ${typeof v === 'number' ? fmt(v) : v}`).join(', ');
      return `    ${layer}:${' '.repeat(Math.max(1, 8 - layer.length))}{ ${body} },`;
    });
    const prog = progressionFor(HARMONY.progressions[s.role === 'climax' ? feel.climax : feel.verse], key);
    return `  section('${s.name}', ${s.share * unit}, { role: '${s.role}', progression: '${prog}',\n${parts.join('\n')}\n  }),`;
  });
  return `// generated by gen/form.mjs --mood=${mood} --bars=${bars} --seed=${seed}: ${mood}, in ${key} at ${feel.bpm} bpm on the ${kit}.
// Next, material first: write notes for melody and bass, pick pack instruments as sound, add a melody2 counter-line in the drop.
song({ bpm: ${feel.bpm}, key: '${key}', seed: ${seed}, kit: '${kit}' }, [
${sections.join('\n')}
])
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opt = (k, d) => { const a = process.argv.find((a) => a.startsWith(`--${k}=`)); return a ? a.slice(k.length + 3) : d; };
  try { process.stdout.write(generate(Number(opt('seed', 1)), { mood: opt('mood', 'euphoric'), bars: Number(opt('bars', 64)) })); }
  catch (e) { console.error(e.message); process.exit(2); }
}
